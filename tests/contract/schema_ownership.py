"""Who owns each file under ``docs/schemas/`` (PADR ADR-008; Foundation task 1.4).

- ``Owned``: miAssist generates it from ``src/miassist/contracts/``
  (``scripts/write_contracts.py``); the sync test regenerates and compares bytes.
- ``Vendored``: a byte-identical copy of a sibling's file, compared through
  ``tests/support/siblings.py`` (skips loudly when the sibling is absent; fails under a require
  switch).

A file in ``docs/schemas/`` with no entry here FAILS: an unowned schema has nobody keeping it true.
``docs/schemas/README.md``'s table must name the same files with the same owner.
"""

from __future__ import annotations

from dataclasses import dataclass

from tests.support import siblings


@dataclass(frozen=True)
class Owned:
    """Generated by ``scripts/write_contracts.py``; ``name`` is its key there."""

    name: str


@dataclass(frozen=True)
class Vendored:
    """A byte copy of ``sibling``'s ``path``."""

    sibling: siblings.Sibling
    path: str


#: Feature 001 fills this: the two owned contracts (1.4), miServer's hints (4.6) and miWorkbench
#: 045's payload vectors (5.2a, push 001-V).
OWNERSHIP: dict[str, Owned | Vendored] = {
    "mistudio-result-language-v1.json": Owned("result_language"),
    "mistudio-playbook-v1.json": Owned("playbook"),
    "next-tool-hints.json": Vendored(siblings.MISERVER, "docs/schemas/next-tool-hints.json"),
    # ENH-013 006-1: miServer's answer contract (MA1); its answers are read from it, not hand records.
    "miserver-answers-v1.json": Vendored(
        siblings.MISERVER, "docs/schemas/miserver-answers-v1.json"
    ),
    "miworkbench-approval-payload-vectors-v1.json": Vendored(
        siblings.MIWORKBENCH, "docs/schemas/miworkbench-approval-payload-vectors-v1.json"
    ),
}

#: Files in docs/schemas/ that are not schemas.
NOT_SCHEMAS = frozenset({"README.md"})
