"""Generate miAssist's two published contracts from ``src/miassist/contracts/`` (001 FTASKS 1.3).

    python -m scripts.write_contracts          # write both files under docs/schemas/
    python -m scripts.write_contracts --check  # exit 1 when a file differs from what is generated

The output is deterministic: ``render(name)`` returns the exact bytes, and the schema-sync test
compares them with the committed file. Never hand-edit the files.

What the generator adds to Pydantic's schemas (FTDD §4.3): the contract's ``$defs`` names (lower
snake case), ``$schema`` (2020-12), ``$id``, ``x-contract``, ``x-error-text-format`` (its line-1
pattern embeds ``$defs.error_code``'s), ``x-annotation-rules`` (from ``annotation_rules.yaml``), and
the playbook file's two relative ``$ref``s into the result-language file. Pydantic's per-property
``title`` annotations are dropped (field names say it); model titles become the contract names.
"""

from __future__ import annotations

import argparse
import json
import sys
from importlib import resources
from pathlib import Path
from types import ModuleType
from typing import Any

import yaml
from pydantic import create_model

from miassist.contracts import playbook, result_language

REPO_ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = REPO_ROOT / "docs" / "schemas"
ID_BASE = "https://raw.githubusercontent.com/hitsainet/miAssist/main/docs/schemas/"
DRAFT = "https://json-schema.org/draft/2020-12/schema"

MODULES: dict[str, ModuleType] = {
    "result_language": result_language,
    "playbook": playbook,
}
TITLES = {
    "result_language": "miStudio result language, v1",
    "playbook": "miStudio playbook, v1",
}
DESCRIPTIONS = {
    "result_language": (
        "The suite's result language: the fields every suite tool's result may carry (approval, "
        "next_steps, unavailable with its reason), the error body and its text format, miAssist's "
        "own result shape, and the MCP annotation rules every suite server's tests read. Owned by "
        "miAssist; consumers vendor this file byte-identical. Generated by "
        "scripts/write_contracts.py; do not edit."
    ),
    "playbook": (
        "A miAssist playbook definition and the status shape its provider returns. Text fields are "
        "keys into the playbook's guidance file. Owned by miAssist. Generated by "
        "scripts/write_contracts.py; do not edit."
    ),
}


def _data(name: str) -> Any:
    raw = resources.files("miassist.contracts").joinpath(name).read_text(encoding="utf-8")
    return yaml.safe_load(raw)


def _strip_titles(node: Any) -> Any:
    """Drop Pydantic's ``title`` annotations and fold descriptions onto one line (docstrings
    wrap). A ``properties`` map's KEYS are field names (a field may be called ``title``): kept."""
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "properties" and isinstance(value, dict):
                out[key] = {k: _strip_titles(v) for k, v in value.items()}
            elif key == "title" and isinstance(value, str):
                continue
            elif key == "description" and isinstance(value, str):
                out[key] = " ".join(value.replace("``", "`").split())
            else:
                out[key] = _strip_titles(value)
        return out
    if isinstance(node, list):
        return [_strip_titles(item) for item in node]
    return node


def _rewrite_refs(node: Any, mapping: dict[str, str], inline: dict[str, Any]) -> Any:
    if isinstance(node, dict) and "x-external-ref" in node:
        ref = {"$ref": f"{playbook.RESULT_LANGUAGE_FILE}#/$defs/{node['x-external-ref']}"}
        return {"anyOf": [ref, {"type": "null"}]} if node.get("x-nullable") else ref
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/$defs/"):
            target = ref.removeprefix("#/$defs/")
            if target in inline:
                merged = {k: v for k, v in node.items() if k != "$ref"}
                return {**_rewrite_refs(inline[target], mapping, inline), **merged}
            return {**node, "$ref": f"#/$defs/{mapping[target]}"}
        return {k: _rewrite_refs(v, mapping, inline) for k, v in node.items()}
    if isinstance(node, list):
        return [_rewrite_refs(item, mapping, inline) for item in node]
    return node


def build(name: str) -> dict[str, Any]:
    """The contract ``name`` (``result_language`` or ``playbook``) as a JSON-ready dict."""
    module = MODULES[name]
    defs_by_contract: dict[str, type[Any]] = module.DEFS
    # One throwaway container with a field per def, so enums and root models get named $defs too.
    container = create_model(  # type: ignore[call-overload]
        "_Contract", **{contract: (model, ...) for contract, model in defs_by_contract.items()}
    )
    generated = container.model_json_schema(ref_template="#/$defs/{model}")
    raw_defs: dict[str, Any] = generated.get("$defs", {})
    mapping = {model.__name__: contract for contract, model in defs_by_contract.items()}
    unknown = set(mapping) - set(raw_defs)
    if unknown:
        raise RuntimeError(f"models missing from the generated schema: {sorted(unknown)}")
    inline = {k: v for k, v in raw_defs.items() if k not in mapping}
    defs = {
        mapping[cls.__name__]: _strip_titles(_rewrite_refs(raw_defs[cls.__name__], mapping, inline))
        for cls in defs_by_contract.values()
    }
    file_name: str = module.FILE_NAME
    doc: dict[str, Any] = {
        "$schema": DRAFT,
        "$id": ID_BASE + file_name,
        "title": TITLES[name],
        "description": DESCRIPTIONS[name],
        "x-contract": module.CONTRACT,
    }
    if name == "result_language":
        error_text = dict(_data("error_text.yaml"))
        code = defs["error_code"]["pattern"].removeprefix("^").removesuffix("$")
        error_text["lines"] = [
            {**line, "pattern": line["pattern"].replace("{error_code}", code)}
            for line in error_text["lines"]
        ]
        doc["x-error-text-format"] = error_text
        doc["x-annotation-rules"] = _data("annotation_rules.yaml")
    doc["$ref"] = f"#/$defs/{module.ROOT}"
    doc["$defs"] = defs
    return doc


def render(name: str) -> bytes:
    """The exact bytes of the contract ``name``'s file."""
    return (json.dumps(build(name), indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def file_for(name: str) -> Path:
    file_name: str = MODULES[name].FILE_NAME
    return SCHEMAS / file_name


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    stale = []
    for name in MODULES:
        path, data = file_for(name), render(name)
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(path.name)
        else:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    if stale:
        print(f"stale: {', '.join(stale)}; run python -m scripts.write_contracts", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
