"""Write each playbook's skill package (001 FR-5, AC-5.8; FTASKS 11.4).

``python -m scripts.write_skills [--out build/skills] [--definitions DIR]`` writes
``<out>/<playbook id>/SKILL.md`` for EVERY shipped definition (generated by
``miassist.playbooks.generate.skill_markdown``, the same function the server's
``miassist://skills/<id>`` resource uses), resolved as if all four apps were installed. A
definition that does not validate, or names a text key its words file lacks, exits non-zero and
writes nothing.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from miassist.guidance.loader import Guidance
from miassist.playbooks import generate
from miassist.playbooks.registry import PlaybookError, load
from miassist.tools import all_specs

APPS = ("miworkbench", "miserver", "midataworks", "miforge")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="build/skills")
    parser.add_argument("--definitions", default=None)
    args = parser.parse_args(argv)
    words = Guidance()
    tools = [s.name for s in all_specs() if s.offered(frozenset(APPS))]
    try:
        registry = load(words, APPS, tools, Path(args.definitions) if args.definitions else None)
    except PlaybookError as exc:
        raise SystemExit(f"write_skills: {exc.code}") from None
    out = Path(args.out)
    for playbook in registry.playbooks.values():
        target = out / playbook.id / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generate.skill_markdown(words, playbook), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
